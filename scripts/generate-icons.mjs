// Writes src/data/tablerIcons.ts: the name of every Tabler icon, read from the installed
// @tabler/icons-webfont's stylesheet (one `.ti-{name}:before` rule per icon), for TIconPicker.
// Run it after updating @tabler/icons-webfont: npm run icons
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const css = readFileSync(`${root}node_modules/@tabler/icons-webfont/dist/tabler-icons.css`, 'utf8')
const { version } = JSON.parse(readFileSync(`${root}node_modules/@tabler/icons-webfont/package.json`, 'utf8'))
const names = [...new Set([...css.matchAll(/^\.ti-([a-z0-9-]+):before/gm)].map(m => m[1]))].sort()

writeFileSync(`${root}src/data/tablerIcons.ts`, `// Generated by scripts/generate-icons.mjs from @tabler/icons-webfont ${version}: every Tabler icon's
// name (${names.length}), for TIconPicker. Don't edit; run \`npm run icons\` after updating the icons.
export const tablerIconsVersion = '${version}'

export const tablerIcons: readonly string[] = '${names.join(' ')}'.split(' ')
`)
console.log(`${names.length} icons from @tabler/icons-webfont ${version}.`)
